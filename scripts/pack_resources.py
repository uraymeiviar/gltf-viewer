#!/usr/bin/env python3
"""
Packs runtime resources (shaders, fonts, environments, sampleGltf)
into a single compressed binary archive using Zstandard (zstd), and emits
a C++ source file (EmbeddedResources.cpp) with the embedded archive bytes.
"""

import os
import sys
import struct
import zstandard

def pack_resources(resources_dir, output_zst_path, output_cpp_path):
    subdirs = ["shaders", "fonts", "environments", "sampleGltf"]
    files_to_pack = []

    for subdir in subdirs:
        dir_path = os.path.join(resources_dir, subdir)
        if not os.path.isdir(dir_path):
            continue
        for root, _, filenames in os.walk(dir_path):
            for fn in filenames:
                full_path = os.path.join(root, fn)
                rel_path = os.path.relpath(full_path, resources_dir).replace("\\", "/")
                # Skip temporary or unwanted files
                if fn.startswith(".") or fn.endswith(".tmp") or fn.endswith(".bak"):
                    continue
                files_to_pack.append((rel_path, full_path))

    files_to_pack.sort(key=lambda x: x[0])
    print(f"[ResourcePacker] Found {len(files_to_pack)} runtime files to pack.")

    # Build File Table & Payload
    table_bytes = bytearray()
    payload_bytes = bytearray()

    for rel_path, full_path in files_to_pack:
        with open(full_path, "rb") as f:
            data = f.read()

        path_utf8 = rel_path.encode("utf-8")
        offset = len(payload_bytes)
        size = len(data)

        # uint16_t path_len, path_str, uint32_t offset, uint32_t size
        table_bytes += struct.pack("<H", len(path_utf8))
        table_bytes += path_utf8
        table_bytes += struct.pack("<II", offset, size)

        payload_bytes += data

    # Header: Magic "GVFS", version 1, file_count, table_size, payload_size
    magic = b"GVFS"
    version = 1
    file_count = len(files_to_pack)
    table_size = len(table_bytes)
    payload_size = len(payload_bytes)

    header_bytes = struct.pack("<4sIIII", magic, version, file_count, table_size, payload_size)
    raw_archive = header_bytes + table_bytes + payload_bytes

    print(f"[ResourcePacker] Uncompressed archive size: {len(raw_archive):,} bytes ({len(raw_archive)/1024/1024:.2f} MB)")

    # Compress with Zstandard level 19 (high compression)
    cctx = zstandard.ZstdCompressor(level=19)
    compressed_bytes = cctx.compress(raw_archive)
    print(f"[ResourcePacker] Compressed archive size: {len(compressed_bytes):,} bytes ({len(compressed_bytes)/1024/1024:.2f} MB)")
    print(f"[ResourcePacker] Compression ratio: {len(compressed_bytes) / len(raw_archive) * 100:.1f}%")

    # Write .zst single file
    os.makedirs(os.path.dirname(os.path.abspath(output_zst_path)), exist_ok=True)
    with open(output_zst_path, "wb") as f:
        f.write(compressed_bytes)

    # Write C++ source file
    os.makedirs(os.path.dirname(os.path.abspath(output_cpp_path)), exist_ok=True)
    with open(output_cpp_path, "w", encoding="utf-8") as f:
        f.write("// Auto-generated by scripts/pack_resources.py - DO NOT EDIT\n")
        f.write("#include <cstddef>\n")
        f.write("#include <cstdint>\n\n")
        f.write("extern \"C\" {\n")
        f.write("alignas(16) extern const uint8_t g_embeddedResourcesArchive[] = {\n")

        line = []
        for i, b in enumerate(compressed_bytes):
            line.append(f"0x{b:02x}")
            if len(line) >= 16:
                f.write("    " + ", ".join(line) + ",\n")
                line = []
        if line:
            f.write("    " + ", ".join(line) + ",\n")

        f.write("};\n\n")
        f.write("extern const size_t g_embeddedResourcesArchiveSize = sizeof(g_embeddedResourcesArchive);\n")
        f.write("}\n")

    print(f"[ResourcePacker] Successfully generated {output_zst_path} and {output_cpp_path}")

if __name__ == "__main__":
    repo_root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    resources_dir = os.path.join(repo_root, "resources")
    out_zst = os.path.join(resources_dir, "resources.vfs.zst")
    out_cpp = os.path.join(repo_root, "source", "imgui", "EmbeddedResources.cpp")

    if len(sys.argv) >= 2:
        resources_dir = sys.argv[1]
    if len(sys.argv) >= 3:
        out_zst = sys.argv[2]
    if len(sys.argv) >= 4:
        out_cpp = sys.argv[3]

    pack_resources(resources_dir, out_zst, out_cpp)
