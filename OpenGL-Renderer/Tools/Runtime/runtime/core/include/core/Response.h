#pragma once

namespace ux3d::core {
/// A response is a binary sum type over an success type indicating and an error type, indicating success or failure
/// of some computation respectively.
/// It is a general pattern that the error type is an enumeration of error codes, but this is in no way required.
///
/// When a computation can only fail or succeed but does not carry any additional information,
/// use `BoolResponse`, the drop-in replacement for `bool` combined with a error description.
///
/// @note Neither the success type nor the error type need to be default constructible or to implement
/// the assignment operator.
template <class T, class E>
class Response {
public:
    using success_type = T;
    using error_type = E;

    /// Construct from an value, yielding an success response.
    Response(const T& _rhs);

    /// Construct from an rvalue, yielding an success response.
    Response(T&& _rhs);

    /// Construct from an value, yielding an Error response.
    explicit Response(const E& _rhs);

    explicit Response(E _rhs);

    /// Construct from an rvalue, yielding an Error response.
    Response(E&& _rhs);

    /// Variadic success constructor.
    template <class... Args, typename = std::enable_if_t<
                                 // construct if success-Type T is constructible from Args but Error-Type E is not constructible from Args
                                 std::is_constructible_v<T, Args...> && !std::is_constructible_v<E, Args...> &&
                                 // dont construct success-Type T from other Response<T,E> that could host Error value (force use of copy/move constructor instead)
                                 !std::is_same_v<Response<T, E>, std::remove_cv_t<std::remove_reference_t<Args>>...>>>
    Response(Args&&... _args)
        : m_holdsSuccess { true }
        , m_success { std::forward<Args>(_args)... }
    {
    }

    /// Copy construct the response.
    /// The hold value is copy constructed as expected.
    Response(const Response& _rhs);

    /// Move construct the response.
    /// The hold value is move constructed as expected.
    Response(Response&& _rhs) noexcept;

    /// Destructs this response.
    /// Calls the appropriate destructor for the held value.
    ~Response();

    /// Check if success type is held or not.
    explicit operator bool() const
    {
        return m_holdsSuccess;
    }

    /// Access the underlying success type without checking that the success type is actually held.
    /// @warning This is unsafe by design. Nothing prevents you from accessing the success value out of a response
    /// which actually holds an error. You are required to check the response beforehand.
    const T& operator*() const
    {
        return m_success;
    }

    /// Access the underlying success type without checking that the success type is actually held.
    /// @warning This is unsafe access by design.
    T& operator*()
    {
        return m_success;
    }

    /// Access the underlying success type without checking that the success type is actually held.
    /// @warning This is unsafe access by design.
    const T* operator->() const
    {
        return &m_success;
    }

    /// Access the underlying success type without checking that the success type is actually held.
    /// @warning This is unsafe access by design.
    T* operator->()
    {
        return &m_success;
    }

    /// Moves the success value out of this response without checking that the success type is actually held.
    /// @warning This is unsafe access by design.
    T&& unwrap();

    /// Get the error value without checking that the error type is actually held.
    /// @warning This is unsafe access by design.
    const E& error() const;

    /// Get the error value without checking that the error type is actually held.
    /// @warning This is unsafe access by design.
    E& error();

    /// If this response is success, calls `f` on its success value, returning the response generated by `f`.
    /// `f` is expected to return the same response type.
    /// If this response is error, than this error response is returned instead, and `f` is not called.
    template <class F>
    Response andThen(F&& _f) const;

    /// Returns this response if it is success.
    /// Otherwise, `alternative` is returned, whether or not `alternative` is success.
    Response orElse(const Response& _alternative) const;

    /// Returns this response if it is success.
    /// Otherwise, `alternative` is returned.
    const T& orDefault(const T& _alternative) const;

private:
    /// Flag if this response is success or error.
    bool m_holdsSuccess;

    union {
        T m_success;
        E m_error;
    };
}; // !Response

/// A type holding only one value and thus no information.
/// Required by the `BoolResponse`, as it does not hold any information about the success type.
struct SuccessResponse {
};

/// Represents failure or success, while the success does not carry additional information.
/// Generally used when a function would return `bool`, i.e. indicating success but no further data.
template <class E>
using BoolResponse = Response<SuccessResponse, E>;

//////////////////////////////////////////////////////////////////////////////////////////////////////
/// Implementation
//////////////////////////////////////////////////////////////////////////////////////////////////////

template <class T, class E>
inline Response<T, E>::Response(const T& _rhs)
    : m_holdsSuccess { true }
    , m_success { _rhs }
{
}

template <class T, class E>
inline Response<T, E>::Response(T&& _rhs)
    : m_holdsSuccess { true }
    , m_success { std::move(_rhs) }
{
}

template <class T, class E>
inline Response<T, E>::Response(const E& rhs)
    : m_holdsSuccess { false }
    , m_error { rhs }
{
}

template <class T, class E>
inline Response<T, E>::Response(const E _rhs)
    : m_holdsSuccess { false }
    , m_error { _rhs }
{
}

template <class T, class E>
inline Response<T, E>::Response(E&& rhs)
    : m_holdsSuccess { false }
    , m_error { std::move(rhs) }
{
}

template <class T, class E>
inline Response<T, E>::Response(const Response& _rhs)
    : m_holdsSuccess { _rhs.m_holdsSuccess }
{
    if (m_holdsSuccess) {
        new (&m_success) T { _rhs.m_success };
    } else {
        new (&m_error) E { _rhs.m_error };
    }
}

template <class T, class E>
inline Response<T, E>::Response(Response&& _rhs) noexcept
    : m_holdsSuccess { _rhs.m_holdsSuccess }
{
    if (m_holdsSuccess) {
        new (&m_success) T { std::move(_rhs.m_success) };
    } else {
        new (&m_error) E { std::move(_rhs.m_error) };
    }
}

template <class T, class E>
inline Response<T, E>::~Response()
{
    if (m_holdsSuccess) {
        m_success.~T();
    } else {
        m_error.~E();
    }
}

template <class T, class E>
inline const E& Response<T, E>::error() const
{
    return m_error;
}

template <class T, class E>
inline E& Response<T, E>::error()
{
    return m_error;
}

template <class T, class E>
inline Response<T, E> Response<T, E>::orElse(const Response& _alternative) const
{
    return m_holdsSuccess ? *this : _alternative;
}

template <class T, class E>
inline const T& Response<T, E>::orDefault(const T& _alternative) const
{
    return m_holdsSuccess ? m_success : _alternative;
}

template <class T, class E>
inline T&& Response<T, E>::unwrap()
{
    return std::move(m_success);
}

template <class T, class E>
template <class F>
inline Response<T, E> Response<T, E>::andThen(F&& _f) const
{
    return m_holdsSuccess ? std::forward<F>(_f)(m_success) : *this;
}
} // !ux3d::core
