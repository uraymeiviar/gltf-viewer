#pragma once

#include "core/String.h"
#include "core/Vector.h"
#include <optional>
#include <stdint.h>

namespace ux3d::gltf {
class ChildOfRoot;

enum class FileContainer : uint32_t {
    Gltf,
    Glb
};

enum class ConversionUsage : uint32_t {
    ProjectFile,
    ValidGltf,
    StateHistory
};

struct ExportOptions {
    FileContainer fileContainer = FileContainer::Gltf;
    std::optional<core::string> generatorNameOverride = std::optional<core::string>();
    std::optional<core::string> versionOverride = "2.0";
    core::Vector<const ChildOfRoot*> exportCandidates = core::Vector<const ChildOfRoot*>();
    ConversionUsage conversionUsage = ConversionUsage::ProjectFile;
    bool overwriteResourceFiles = true;
    bool writeTimeStamp = true;
    bool writeToMemory = false;
    bool printLogOutput = true;
    bool storeAutogeneratedNames = false;
    bool saveMinified = false;
    bool replaceOriginalBufferUri = true;
};
}
