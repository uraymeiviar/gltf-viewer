using namespace ux3d;
using namespace ux3d::gltf;

void ImagesToJson::convert(const Image& _image, nlohmann::json& _jsonImage, const JsonPath& _jsonPath) const
{
    convertBase(_image, _jsonImage);
    convertName(_image, _jsonImage);
    convertUri(_image, _jsonImage);
    convertMimeType(_image, _jsonImage);
    convertBufferView(_image, _jsonImage);
    convertXMP(_image, _jsonImage);

    if (m_exportOptions.conversionUsage == ConversionUsage::StateHistory || m_exportOptions.conversionUsage == ConversionUsage::ProjectFile) {
        convertStorageFormat(_image, _jsonImage);
        convertBackupUri(_image, _jsonImage);
        if (m_exportOptions.conversionUsage == ConversionUsage::StateHistory) {
            convertImageSize(_image, _jsonImage);
            convertImageCompression(_image, _jsonImage);
        }
        convertMapId(_image, _jsonImage);
    }

    m_resourceCollector.add(_image);
}

void ImagesToJson::convertName(const Image& _image, nlohmann::json& _jsonImage) const
{
    if (m_exportOptions.storeAutogeneratedNames && !_image.hasName()) {
        const core::string uri = _image.getUri();
        if (!uri.empty() && !gltf::embedded_data::isDataUri(uri)) {
            size_t lastDot = uri.find_last_of(".");
            lastDot = lastDot == core::string::npos ? uri.length() - 1 : lastDot;

            size_t lastSlash = uri.find_last_of("/");
            lastSlash = lastSlash == core::string::npos ? 0 : lastSlash + 1;

            _jsonImage["name"] = uri.substr(lastSlash, lastDot - lastSlash);
        }
    }
}

void ImagesToJson::convertMapId(const Image& _image, nlohmann::json& _jsonImage) const
{
    _jsonImage["extensions"]["ux3d_gestaltor"]["mapId"] = _image.encodedMapID;
}

void ImagesToJson::convertUri(const Image& _image, nlohmann::json& _jsonImage) const
{
    if (_image.getUri().size() > 0) {
        _jsonImage["uri"] = _image.getUri();
    }
}

void ImagesToJson::convertMimeType(const Image& _image, nlohmann::json& _jsonImage) const
{
    if (!Image::isValidEncoding(_image.getMimeType())) {
        return;
    }

    _jsonImage["mimeType"] = imageformats::imageEncodingToString(_image.getMimeType());
}

void ImagesToJson::convertBufferView(const Image& _image, nlohmann::json& _jsonImage) const
{
    if (_image.getBufferView() == nullptr) {
        return;
    }
    if (_image.getStorageFormat() != StorageFormat::BufferView) {
        return;
    }

    size_t index = m_indices[_image.getBufferView()];
    _jsonImage["bufferView"] = index;
}

void ImagesToJson::convertStorageFormat(const Image& _image, nlohmann::json& _jsonImage) const
{
    if (_image.getStorageFormat() != StorageFormat::Undefined) {
        _jsonImage["extensions"]["ux3d_gestaltor"]["storageFormat"] = storageFormatToString(_image.getStorageFormat());
    }
}

void ImagesToJson::convertBackupUri(const Image& _image, nlohmann::json& _jsonImage) const
{
    if (!_image.getUri().empty()) {
        _jsonImage["extensions"]["ux3d_gestaltor"]["backupUri"] = _image.getUri();
    }
}

void ImagesToJson::convertImageSize(const Image& _image, nlohmann::json& _jsonImage) const
{
    _jsonImage["extensions"]["ux3d_gestaltor"]["width"] = _image.getData().getWidth();
    _jsonImage["extensions"]["ux3d_gestaltor"]["height"] = _image.getData().getHeight();
}

void ImagesToJson::convertImageCompression(const Image& _image, nlohmann::json& _jsonImage) const
{
    if (std::holds_alternative<image::KTXMetaData>(_image.getData().m_metaData)) {
        auto& metaData = std::get<image::KTXMetaData>(_image.getData().m_metaData);
        _jsonImage["extensions"]["ux3d_gestaltor"]["ktxEtc1sQualityLevel"] = metaData.etc1sQualityLevel;
        _jsonImage["extensions"]["ux3d_gestaltor"]["ktxEtc1sCompressionLevel"] = metaData.etc1sCompressionLevel;
        _jsonImage["extensions"]["ux3d_gestaltor"]["ktxUastcQualityLevel"] = metaData.uastcQualityLevel;
        _jsonImage["extensions"]["ux3d_gestaltor"]["ktxUastcRDO"] = metaData.uastcRDO;
        _jsonImage["extensions"]["ux3d_gestaltor"]["ktxZstdCompressionLevel"] = metaData.zstdCompressionLevel;
        _jsonImage["extensions"]["ux3d_gestaltor"]["ktxColorPrimaries"] = metaData.colorPrimaries;
        _jsonImage["extensions"]["ux3d_gestaltor"]["ktxColorModel"] = metaData.colorModel;
        _jsonImage["extensions"]["ux3d_gestaltor"]["ktxTransferFunction"] = metaData.transferFunction;
        _jsonImage["extensions"]["ux3d_gestaltor"]["ktxSupercompressionScheme"] = metaData.supercompressionSchema;
    }
    if (std::holds_alternative<image::JPEGMetaData>(_image.getData().m_metaData)) {
        auto& metaData = std::get<image::JPEGMetaData>(_image.getData().m_metaData);
        _jsonImage["extensions"]["ux3d_gestaltor"]["jpegCompression"] = metaData.compressionRate;
    }
}

void ImagesToJson::convertXMP(const Image& _image, nlohmann::json& _jsonImage) const
{
    if (_image.hasXMPPacket()) {
        const PacketContainer& container = _image.getXMPPacket().value();
        Packet* pPacket = container.m_packet;
        if (m_gltf.getXMP().has_value()) {
            const XMP& xmp = m_gltf.getXMP().value();
            const core::LinkedList<Packet>& packets = xmp.getPackets();

            for (size_t i = 0; i < packets.size(); ++i) {
                if (&packets.at(i) == pPacket) {
                    _jsonImage["extensions"]["KHR_xmp_json_ld"]["packet"] = i;
                    break;
                }
            }
        }

        // convert extras and extensions
        GltfObjectToJson gltfObjectToJson(m_exportOptions);
        gltfObjectToJson.convertExtras(container, _jsonImage["extensions"]["KHR_xmp_json_ld"]);
        gltfObjectToJson.convertUnknownExtensions(container, _jsonImage["extensions"]["KHR_xmp_json_ld"]);
    }
}
